COLORS = {"Slow": "#4361ee", "Base": "#079b91", "Fast": "#e69c36"}


def project_cash_flows(cpr):
    """Project a homogeneous pool with proportional full-loan prepayments.

    Surviving loans retain their contractual amortization schedules.
    Aggregate payments decline as prepaid loans leave the pool.
    """
    if not 0 <= cpr <= 1:
        raise ValueError("CPR must be between zero and one.")
    if not 0 <= SERVICING_FEE <= MORTGAGE_RATE:
        raise ValueError("Servicing fee must be between zero and note rate.")
    if INITIAL_BALANCE <= 0 or REMAINING_MONTHS <= 0:
        raise ValueError("Balance and remaining term must be positive.")

    monthly_rate = MORTGAGE_RATE / 12
    smm = 1 - (1 - cpr) ** (1 / 12)
    balance = INITIAL_BALANCE
    rows = []

    for month in range(1, REMAINING_MONTHS + 1):
        remaining = REMAINING_MONTHS - month + 1

        if monthly_rate == 0:
            payment = balance / remaining
        else:
            payment = (
                balance * monthly_rate
                / (1 - (1 + monthly_rate) ** -remaining)
            )

        gross_interest = balance * monthly_rate
        servicing = balance * SERVICING_FEE / 12
        scheduled_principal = min(
            balance, max(0.0, payment - gross_interest)
        )

        if month == REMAINING_MONTHS:
            scheduled_principal = balance

        prepayment = (balance - scheduled_principal) * smm
        ending_balance = max(
            0.0, balance - scheduled_principal - prepayment
        )
        investor_interest = gross_interest - servicing
        investor_cash_flow = (
            investor_interest + scheduled_principal + prepayment
        )

        rows.append({
            "Month": month,
            "Beginning balance": balance,
            "Scheduled payment": payment,
            "Gross interest": gross_interest,
            "Servicing fee": servicing,
            "Investor interest": investor_interest,
            "Scheduled principal": scheduled_principal,
            "Voluntary prepayment": prepayment,
            "Investor cash flow": investor_cash_flow,
            "Ending balance": ending_balance,
        })
        balance = ending_balance

    return pd.DataFrame(rows)


def present_value(cash_flows, annual_discount_rate):
    """Discount month-end payments using nominal monthly compounding."""
    if annual_discount_rate <= -12:
        raise ValueError("Invalid discount rate.")

    return float(np.sum(
        cash_flows["Investor cash flow"].to_numpy()
        / (1 + annual_discount_rate / 12)
        ** cash_flows["Month"].to_numpy()
    ))


def yield_at_price(cash_flows, purchase_price):
    """Solve nominal annual cash-flow yield by bisection."""
    if purchase_price <= 0:
        raise ValueError("Purchase price must be positive.")

    lower, upper = -0.90, 1.0
    while present_value(cash_flows, upper) > purchase_price:
        upper *= 2

    for _ in range(120):
        middle = (lower + upper) / 2
        if present_value(cash_flows, middle) > purchase_price:
            lower = middle
        else:
            upper = middle

    return (lower + upper) / 2


def validate(flows):
    messages = []
    net_coupon = MORTGAGE_RATE - SERVICING_FEE

    for name, cf in flows.items():
        principal = (
            cf["Scheduled principal"] + cf["Voluntary prepayment"]
        )
        assert np.allclose(
            cf["Beginning balance"] - principal,
            cf["Ending balance"],
            atol=1e-7,
        )
        assert np.isclose(
            principal.sum(), INITIAL_BALANCE, atol=0.01
        )
        assert cf["Ending balance"].iloc[-1] < 0.01
        assert (cf.select_dtypes("number") >= -1e-8).all().all()
        assert np.allclose(
            cf["Investor cash flow"],
            cf["Investor interest"] + principal,
        )
        assert np.isclose(
            present_value(cf, net_coupon),
            INITIAL_BALANCE,
            atol=0.01,
        )
        assert present_value(cf, 0.05) > present_value(cf, 0.07)
        messages.append(
            f"{name}: principal conservation, balance roll-forward, "
            "maturity payoff, par identity and PV monotonicity passed."
        )

    zero_cpr = project_cash_flows(0)
    r = MORTGAGE_RATE / 12
    payment = (
        INITIAL_BALANCE / REMAINING_MONTHS
        if r == 0 else
        INITIAL_BALANCE * r / (1 - (1 + r) ** -REMAINING_MONTHS)
    )
    assert np.allclose(
        zero_cpr["Scheduled payment"], payment,
        rtol=1e-7, atol=0.01,
    )
    messages.append("Zero-CPR contractual amortization passed.")
    return messages


def write_excel(summary, sensitivity, flows):
    path = OUTPUT_DIR / "mortgage_pool_report.xlsx"

    with pd.ExcelWriter(path, engine="xlsxwriter") as writer:
        tables = {
            "Summary": summary,
            "Sensitivity": sensitivity,
            **{f"{name} Cash Flow": cf for name, cf in flows.items()},
        }
        for sheet, frame in tables.items():
            frame.to_excel(
                writer, sheet_name=sheet, index=False, startrow=3
            )
            ws = writer.sheets[sheet]
            ws.write(0, 0, "Mortgage Pool | " + sheet)
            ws.write(
                1, 0,
                "Hypothetical inputs. Python-calculated results."
            )
            ws.hide_gridlines(2)
            ws.freeze_panes(4, 1)
            ws.set_column(0, len(frame.columns) - 1, 23)
            ws.add_table(
                3, 0, len(frame) + 3, len(frame.columns) - 1,
                {
                    "style": "Table Style Medium 2",
                    "columns": [
                        {"header": str(c)} for c in frame.columns
                    ],
                },
            )
            numeric = writer.book.add_format({
                "num_format": "#,##0.00"
            })
            percent = writer.book.add_format({
                "num_format": "0.00%"
            })
            for i, column in enumerate(frame.columns):
                fmt = percent if column in {
                    "CPR", "SMM", "Discount rate",
                    "Nominal yield", "Effective annual yield",
                } else numeric
                if pd.api.types.is_numeric_dtype(frame[column]):
                    ws.set_column(i, i, 23, fmt)

        assumptions = pd.DataFrame([
            ["Pool balance", INITIAL_BALANCE, "USD"],
            ["Mortgage rate", MORTGAGE_RATE, "Annual decimal"],
            ["Remaining term", REMAINING_MONTHS, "Months"],
            ["Servicing fee", SERVICING_FEE, "Annual decimal"],
            ["Base discount", BASE_DISCOUNT_RATE, "Annual decimal"],
            *[
                [f"{name} CPR", cpr, "Annual decimal"]
                for name, cpr in PREPAYMENT_SCENARIOS.items()
            ],
        ], columns=["Assumption", "Value", "Units"])
        assumptions.to_excel(
            writer, sheet_name="Assumptions", index=False
        )
        writer.sheets["Assumptions"].set_column(0, 2, 26)

        ws = writer.book.add_worksheet("Charts")
        ws.hide_gridlines(2)
        for row, filename in zip(
            [1, 31, 61],
            ["balance_chart.png", "cash_flow_chart.png",
             "valuation_chart.png"],
        ):
            ws.insert_image(
                row, 1, str(OUTPUT_DIR / filename),
                {"x_scale": 0.55, "y_scale": 0.55},
            )


def write_charts(flows, sensitivity):
    plt.rcParams.update({
        "font.size": 10,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.titleweight": "bold",
        "axes.grid": True,
        "grid.alpha": 0.18,
    })

    fig, ax = plt.subplots(figsize=(10, 5))
    for name, cf in flows.items():
        ax.plot(
            cf["Month"] / 12,
            cf["Ending balance"] / 1e6,
            color=COLORS[name],
            label=f"{name}: {PREPAYMENT_SCENARIOS[name]:.0%} CPR",
            linewidth=2,
        )
    ax.set(
        title="Prepayments reshape the repayment horizon",
        xlabel="Years",
        ylabel="Remaining principal ($ millions)",
    )
    ax.legend(frameon=False)
    fig.savefig(
        OUTPUT_DIR / "balance_chart.png", dpi=180,
        bbox_inches="tight",
    )
    plt.close(fig)

    cf = flows["Base"]
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.stackplot(
        cf["Month"] / 12,
        cf["Investor interest"] / 1e6,
        cf["Scheduled principal"] / 1e6,
        cf["Voluntary prepayment"] / 1e6,
        labels=["Net interest", "Scheduled principal", "Prepayment"],
        colors=["#142b45", "#079b91", "#e69c36"],
    )
    ax.set(
        title="Base scenario: investor cash-flow composition",
        xlabel="Years",
        ylabel="Monthly cash flow ($ millions)",
    )
    ax.legend(frameon=False)
    fig.savefig(
        OUTPUT_DIR / "cash_flow_chart.png", dpi=180,
        bbox_inches="tight",
    )
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(10, 5))
    for name in flows:
        ax.plot(
            sensitivity["Discount rate"] * 100,
            sensitivity[name],
            color=COLORS[name], marker="o", label=name,
        )
    ax.axhline(100, color="gray", linestyle="--")
    ax.axvline(
        (MORTGAGE_RATE - SERVICING_FEE) * 100,
        color="gray", linestyle=":",
    )
    ax.set(
        title="Valuation sensitivity to discount rates and CPR",
        xlabel="Nominal annual discount rate (%)",
        ylabel="Price per $100 principal",
    )
    ax.legend(frameon=False)
    fig.savefig(
        OUTPUT_DIR / "valuation_chart.png", dpi=180,
        bbox_inches="tight",
    )
    plt.close(fig)


def write_documentation(summary):
    base = summary.loc[summary["Scenario"] == "Base"].iloc[0]

    note = f"""PURPOSE AND INPUTS
This educational model values a hypothetical fixed-rate mortgage pool:
${INITIAL_BALANCE:,.0f} principal, {MORTGAGE_RATE:.2%} borrower rate,
{REMAINING_MONTHS} months remaining and {SERVICING_FEE:.2%} servicing.
These are illustrative assumptions, not actual loan or security data.

CASH-FLOW METHOD
Scheduled principal follows contractual amortization. Annual CPR is
converted to monthly SMM using 1-(1-CPR)^(1/12). Prepayment is applied
after scheduled principal. Investors receive interest net of servicing,
scheduled principal and prepayments at month end. Full-loan prepayments
reduce the aggregate payment as loans leave the homogeneous pool.

BASE RESULT
At {BASE_DISCOUNT_RATE:.2%} nominal annual discount, the base case values
at ${base['Value']:,.0f}, or {base['Price per 100']:.2f} per $100.
Weighted-average life is {base['WAL years']:.2f} years. The workbook
compares three prepayment scenarios across eight discount rates.

PREPAYMENTS AND VALUE
Faster prepayment returns principal sooner, shortens weighted-average
life and reduces total future interest. When required yield is below
the investor net coupon, early repayment removes premium cash flows
and lowers value. Above net coupon, it returns par sooner and increases
discount value. At net coupon, all scenarios value at par here.

INVESTOR RETURNS
Scenario yields use the same purchase price: base-case PV at the base
discount rate. This isolates the effect of cash-flow timing at a fixed
price. Nominal and effective annual yields are reported separately.
IRR is an internal cash-flow yield. Terminal wealth also depends on
reinvestment rates; undiscounted interest alone is not a return measure.

ASSUMPTION SENSITIVITY AND LIMITS
Higher discount rates or servicing fees lower value. Longer terms
generally extend exposure. Constant CPR omits refinancing incentives,
seasoning, burnout and seasonality. The model excludes defaults,
losses, guarantee fees, payment delays, taxes and trading costs.
Duration holds cash flows fixed and is not option-adjusted.
See methodology.md for equations, checks and detailed limitations.
"""
    paragraphs = [
        "\n".join(textwrap.wrap(" ".join(p.split()), 88))
        for p in note.strip().split("\n\n")
    ]
    fig = plt.figure(figsize=(8.5, 11))
    fig.text(
        0.08, 0.94, "Mortgage Pool Cash Flow & Valuation",
        fontsize=18, weight="bold", color="#142b45",
    )
    fig.text(
        0.08, 0.89, "\n\n".join(paragraphs),
        va="top", fontsize=9.5, linespacing=1.3,
    )
    fig.savefig(OUTPUT_DIR / "project_explanation.pdf")
    plt.close(fig)

    methodology = f"""# Mortgage Pool Cash Flow and Valuation

## Data provenance
All pool inputs are hypothetical and selected for demonstration.
No historical loan-level data, real pool disclosures or market prices
are used. Scenario CPRs are illustrative, not estimated forecasts.

## Assumptions
- Initial balance: ${INITIAL_BALANCE:,.0f}.
- Borrower note rate: {MORTGAGE_RATE:.2%}.
- Remaining term: {REMAINING_MONTHS} months.
- Servicing fee: {SERVICING_FEE:.2%} of beginning balance annually.
- Net investor coupon: {MORTGAGE_RATE-SERVICING_FEE:.2%}.
- CPR scenarios: {PREPAYMENT_SCENARIOS}.
- Base discount: {BASE_DISCOUNT_RATE:.2%}, nominal annual.
- Month-end cash flows; monthly compounding; no remittance delay.
- Homogeneous loans and proportional full-loan prepayments.
- Fractional loan survival is permitted at aggregate pool level.

## Monthly equations
For beginning balance B, n remaining payments and r=note rate/12:
Payment = B*r/[1-(1+r)^(-n)].
Interest = B*r.
Scheduled principal = payment-interest, capped at B.
SMM = 1-(1-CPR)^(1/12).
Prepayment = (B-scheduled principal)*SMM.
Servicing = B*annual fee/12.
Investor cash = interest-servicing+scheduled principal+prepayment.
Ending balance = B-scheduled principal-prepayment.
PV = sum(cash_t/[1+annual discount/12]^t).

Recomputing aggregate payments implements the shrinking population of
surviving identical loans. It does not recast individual surviving loans
after partial principal curtailments. The final month clears principal.

## Metrics and conventions
Price per 100 = PV/initial balance*100.
WAL weights principal repayments by time in years, divided by initial
principal. It is not interest-weighted.
Scenario yields use one common purchase price: the base-case PV.
Effective annual yield = (1+nominal annual yield/12)^12-1.
Total interest is undiscounted and is not itself an investment return.
Fixed-flow duration uses a symmetric 1 bp discount-rate bump, holding
CPR and cash flows constant. It is not option-adjusted duration.
IRR does not guarantee reinvestment at that yield.

## How assumptions change results
Higher CPR lowers WAL and total interest. Below the net coupon, faster
CPR lowers premium value. Above net coupon, faster CPR raises discount
value. At net coupon the simplified pool values at par for any CPR.
Higher discount rates reduce PV. Higher servicing fees reduce net
interest and PV. Increasing balance scales cash flows and dollar value,
but does not change price per 100 or WAL.
Higher note rates generally increase value at fixed CPR and discount,
but real refinancing behavior can offset that benefit.
Longer terms generally extend exposure and discount-rate sensitivity.

## Limitations
No defaults, delinquency, credit losses, guarantee fees, servicing
advances, taxes, transaction costs, security tranches, payment delays
or loan-level dispersion. CPR does not respond to rates, seasonality,
seasoning, burnout or turnover. A flat discount rate replaces a yield
curve. No stochastic rate model or option-adjusted spread is calculated.
Consequently this is not a production trading valuation.

## Verification
The script checks principal conservation, balance roll-forward,
nonnegative cash flows, payoff at maturity, par value at net coupon,
PV monotonicity, zero-CPR amortization and scenario ordering.
Excel is a calculated report; change Python inputs and rerun.
"""
    (OUTPUT_DIR / "methodology.md").write_text(
        methodology, encoding="utf-8"
    )


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    flows = {
        name: project_cash_flows(cpr)
        for name, cpr in PREPAYMENT_SCENARIOS.items()
    }
    checks = validate(flows)
    purchase_price = present_value(flows["Base"], BASE_DISCOUNT_RATE)

    rows = []
    for name, cf in flows.items():
        principal = (
            cf["Scheduled principal"] + cf["Voluntary prepayment"]
        )
        pv = present_value(cf, BASE_DISCOUNT_RATE)
        bump = 0.0001
        duration = (
            present_value(cf, BASE_DISCOUNT_RATE - bump)
            - present_value(cf, BASE_DISCOUNT_RATE + bump)
        ) / (2 * pv * bump)
        nominal_yield = yield_at_price(cf, purchase_price)

        rows.append({
            "Scenario": name,
            "CPR": PREPAYMENT_SCENARIOS[name],
            "SMM": 1 - (1 - PREPAYMENT_SCENARIOS[name]) ** (1 / 12),
            "Value": pv,
            "Price per 100": pv / INITIAL_BALANCE * 100,
            "WAL years": float(np.dot(
                cf["Month"] / 12, principal
            ) / INITIAL_BALANCE),
            "Total investor interest": cf["Investor interest"].sum(),
            "Total prepayment": cf["Voluntary prepayment"].sum(),
            "Fixed-flow duration years": duration,
            "Common purchase price": purchase_price,
            "Nominal yield": nominal_yield,
            "Effective annual yield":
                (1 + nominal_yield / 12) ** 12 - 1,
        })

    summary = pd.DataFrame(rows)
    assert summary["WAL years"].is_monotonic_decreasing
    assert summary["Total investor interest"].is_monotonic_decreasing
    checks.append("WAL and total-interest scenario ordering passed.")

    sensitivity = pd.DataFrame({
        "Discount rate": DISCOUNT_RATES,
        **{
            name: [
                present_value(cf, rate) / INITIAL_BALANCE * 100
                for rate in DISCOUNT_RATES
            ]
            for name, cf in flows.items()
        },
    })

    write_charts(flows, sensitivity)
    write_excel(summary, sensitivity, flows)
    write_documentation(summary)
    summary.to_csv(OUTPUT_DIR / "scenario_summary.csv", index=False)
    sensitivity.to_csv(
        OUTPUT_DIR / "valuation_sensitivity.csv", index=False
    )
    (OUTPUT_DIR / "validation.txt").write_text(
        "\n".join(checks), encoding="utf-8"
    )

    print(summary.to_string(index=False))
    print(f"\nOutputs: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()